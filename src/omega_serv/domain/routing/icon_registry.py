_LITERAL_FILENAME_ICONS = frozenset({"makefile", "dockerfile", "containerfile"})

FALLBACK_ICON = "unknow.svg"
DIRECTORY_ICON = "folder.svg"

ICON_URL_PREFIX = "/.omega-serv-icons/"
"""Chemin URL reserve (meme statut que `/healthz`, verifie tout en haut
de `route_request()` - voir `application/server/serve_icon.py`) sous
lequel les icones sont servies. Vit ici (domain/, pas application/) pour
que `dirlisting.py` (domain, ne peut pas dependre de application/) et
`serve_icon.py` (application) partagent la MEME valeur sans jamais
diverger."""

ICON_FILENAMES: frozenset[str] = (
    frozenset(MIME_ICONS.values()) | frozenset(EXTENSION_ICONS.values()) | {FALLBACK_ICON, DIRECTORY_ICON}
)
"""Ensemble FERME des noms de fichiers icone valides - la seule
"allowlist" que `application/server/serve_icon.py` consulte pour decider
si une requete peut etre servie, jamais une resolution de chemin."""


def icon_for_file(name: str, mime_type: str | None = None, is_directory: bool = False) -> str:
    """Nom de fichier icone (dans `ICON_FILENAMES`) pour l'entree `name`
    d'un directory listing. `mime_type` optionnel et volontairement non
    utilise par l'appelant actuel (dirlisting.py) : la table MIME de
    `domain/http/mime_types.py` est deliberement fermee et etroite
    (19 extensions, pensee pour l'en-tete `Content-Type` reel, jamais
    pour deviner un type) - la lui faire jouer ce role renverrait
    `application/octet-stream` pour la quasi-totalite des fichiers (ex.
    `.py`, `.zip`, `.deb`), qui correspond LUI-MEME a `unknow.svg` dans
    `MIME_ICONS` : predure l'etape d'extension pour presque tout. Le
    parametre reste expose pour un appelant futur dispose d'une
    detection MIME plus large (magic bytes, etc.)."""
    if is_directory:
        return DIRECTORY_ICON

    if mime_type:
        icon = MIME_ICONS.get(mime_type)
        if icon:
            return icon

    path = PurePosixPath(name)
    suffixes = path.suffixes
    for combined in (
        "".join(suffixes[-3:]).lower(),
        "".join(suffixes[-2:]).lower(),
        path.suffix.lower(),
    ):
        if combined in EXTENSION_ICONS:
            return EXTENSION_ICONS[combined]

    if path.name.lower() in _LITERAL_FILENAME_ICONS:
        return "script.svg"

    return FALLBACK_ICON
