"""Selection de l'icone SVG associee a un fichier du directory listing
(retour utilisateur : "incorporer des vrais icones svg").

Module pur (aucune I/O, aucun import externe) : les icones elles-memes
(bytes) sont servies depuis `infrastructure/icons/icon_files.py`, ce
fichier ne choisit qu'un NOM de fichier parmi un ensemble ferme et
connu a l'avance (`ICON_FILENAMES`) - jamais un chemin arbitraire.

Securite (retour utilisateur, recommandation OWASP citee) : un SVG non
fiable peut contenir du script, des gestionnaires d'evenements ou un
`foreignObject` - injecter le contenu SVG directement dans le HTML
(`<div>{{ contenu_svg }}</div>`) executerait ce script. Le modele retenu
ici satisfait les 3 conditions recommandees a la fois :
1. Les icones sont fournies par nous (verifiees, aucun `<script>`/
   gestionnaire d'evenement/`foreignObject` - voir la revue faite avant
   integration), jamais televersees ni modifiables par un utilisateur.
2. Elles vivent dans un repertoire statique du PAQUET Python lui-meme
   (`infrastructure/icons/svg/`), jamais dans l'arborescence servie par
   le site (`project_root`) - aucun utilisateur du serveur ne peut les
   remplacer.
3. Elles sont referencees via `<img src="...">` (dirlisting.py), jamais
   injectees inline dans le HTML - meme un SVG malveillant charge par
   `<img>` ne peut pas executer de script (le navigateur le traite comme
   une image, jamais comme un document HTML/SVG actif).

Selection : MIME type d'abord (formats standards), extension ensuite
(paquets/fichiers systeme dont le MIME type reel est souvent generique -
`application/octet-stream`), puis `unknow.svg` en dernier recours - meme
logique que documentee dans le mapping fourni."""
